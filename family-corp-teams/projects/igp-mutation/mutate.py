# ============================================================
# Agent Scoring
# ============================================================

def score_agent_file(filepath):
    """给一个Agent文件打分"""
    if not os.path.exists(filepath):
        return 0
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    score = 5  # 基础分
    
    # 有class定义 +1
    if 'class ' in content:
        score += 1
    # 有 docstring +1
    if '"""' in content:
        score += 1
    # 有 error handling +1
    if 'try' in content and 'except' in content:
        score += 1
    # 有输出 +1
    if 'print' in content or 'json.dumps' in content:
        score += 1
    # 有主函数 +1
    if '__main__' in content:
        score += 1
    
    return min(10, score)


# ============================================================
# Mutation Engine
# ============================================================

MUTATION_PATTERNS = [
    # Pattern 1: 添加错误处理
    {
        'name': 'error_handling',
        'search': r'result = \{',
        'replace': 'try:\n        result = {',
        'post': '\n    except Exception as e:\n        result = {"error": str(e)}',
        'score_gain': 1,
    },
    # Pattern 2: 添加docstring
    {
        'name': 'docstring',
        'search': r'class (\w+)\(\):\n(?!\s*""")',
        'replace': r'class \1():\n    """\1 - Auto-generated by IGP Mutation"""\n',
        'score_gain': 1,
    },
    # Pattern 3: 添加identify方法加强
    {
        'name': 'enhanced_identify',
        'search': r'"status": "active"',
        'replace': '"status": "active",\n            "mutations": 1,\n            "last_evolved": "' + datetime.now().strftime('%Y-%m-%d %H:%M') + '"',
        'score_gain': 1,
    },
]


def mutate_agent_file(filepath):
    """对一个Agent文件执行基因突变"""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    score_before = score_agent_file(filepath)
    mutations_applied = []
    
    for pattern in MUTATION_PATTERNS:
        if pattern['name'] == 'error_handling':
            # 检查是否已有try
            if 'try:' in content:
                continue
            if pattern['search'] in content:
                # 找到第一个result赋值的位置
                idx = content.find(pattern['search'])
                if idx >= 0:
                    # 找到这一行的缩进
                    line_start = content.rfind('\n', 0, idx) + 1
                    indent = content[line_start:idx]
                    before = content[:line_start] + indent + 'try:\n' + indent + '    '
                    after_insert = content[idx:]
                    # 在对应位置后加 post
                    result_end = after_insert.find('\n', after_insert.find('\n') + 1)
                    rest = after_insert[result_end:]
                    content = before + pattern['search'] + rest + indent + pattern['post'] + '\n'
                    mutations_applied.append(pattern['name'])
        
        elif pattern['name'] == 'docstring':
            import re as re_mod
            new_content = re_mod.sub(pattern['search'], pattern['replace'], content)
            if new_content != content:
                mutations_applied.append(pattern['name'])
                content = new_content
        
        elif pattern['name'] == 'enhanced_identify':
            if pattern['search'] in content:
                content = content.replace(pattern['search'], pattern['replace'], 1)
                mutations_applied.append(pattern['name'])
    
    # 写入文件
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    
    score_after = score_agent_file(filepath)
    
    return {
        'file': os.path.basename(filepath),
        'score_before': score_before,
        'score_after': score_after,
        'mutations': mutations_applied,
        'improved': score_after > score_before,
    }


def mutate_all_agents():
    """突变所有Genesis生成的Agent"""
    results = []
    for f in os.listdir(GENESIS_DIR):
        if f.endswith('.py') and f != 'genesis.py' and f.startswith('dept_'):
            fp = os.path.join(GENESIS_DIR, f)
            result = mutate_agent_file(fp)
            results.append(result)
    return results


# ============================================================
# Generational Comparison
# ============================================================

def compare_generations():
    """比较第N代和第N+1代Agent的分数"""
    results = mutate_all_agents()
    
    print('🧬 IGP Mutation — Agent 基因突变')
    print('=' * 50)
    
    improved = sum(1 for r in results if r['improved'])
    total = len(results)
    
    print(f'\nAgent 数量: {total}')
    print(f'  进化: {improved} 个')
    print(f'  稳定: {total - improved} 个')
    
    print(f'\n📊 世代对比:')
    for r in results:
        sym = '⬆' if r['improved'] else '➡'
        print(f'  {sym} {r["file"]}')
        print(f'     Gen0: {r["score_before"]}/10 → Gen1: {r["score_after"]}/10')
        if r['mutations']:
            print(f'     突变: {", ".join(r["mutations"])}')
    
    # 保存比较结果
    comparison = {
        'generation': 1,
        'timestamp': datetime.now().isoformat(),
        'total_agents': total,
        'evolved': improved,
        'avg_score_before': round(sum(r['score_before'] for r in results) / max(total, 1), 1),
        'avg_score_after': round(sum(r['score_after'] for r in results) / max(total, 1), 1),
        'details': results,
    }
    
    comp_path = os.path.join(MUTATION_DIR, 'generational_comparison.json')
    with open(comp_path, 'w', encoding='utf-8') as f:
        json.dump(comparison, f, ensure_ascii=False, indent=2)
    
    print(f'\n🏆 世代对比: Gen0 {comparison["avg_score_before"]}分 → Gen1 {comparison["avg_score_after"]}分')
    print(f'   (保存: {comp_path})')
    
    return comparison


def main():
    compare_generations()


if __name__ == '__main__':
    main()
